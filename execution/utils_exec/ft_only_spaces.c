#include "../execution.h"

int	is_only_spaces(char *cmd)
{
	int	i;

	if (!cmd || *cmd == 0)
		return (1);
	i = 0;
	while (cmd[i])
	{
		if (cmd[i] != ' ' && cmd[i] != '\t')
			return (0);
		i++;
	}
	return (1);
}
