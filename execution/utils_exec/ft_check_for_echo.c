#include "../execution.h"

int	ft_check(char **str, int *i)
{
	int	j;

	j = 1;
	if (!str[*i] || str[*i][0] != '-' || str[*i][1] != 'n')
		return (0);
	while (str[*i][j] == 'n')
		j++;
	if (str[*i][j] == '\0')
	{
		(*i)++;
		return (1);
	}
	return (0);
}
