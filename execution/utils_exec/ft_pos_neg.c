#include "../execution.h"

int ft_pos_neg(char *str)
{
    int i;

    i = 0;
    while (str[i] != '\0')
    {
        if ((str[i] == '+' || str[i] == '-' || str[i] == '*') && str[i + 1] == '=')
        {
            return (0);
        }
        i++;
    }
    return (1);
}
